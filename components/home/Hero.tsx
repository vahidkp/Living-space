import { getImageProps } from "next/image";
import { ButtonLink } from "@/components/ui/Button";

/**
 * Full-bleed homepage hero (PRD §5.4: 70–85vh, serif headline, single outline
 * CTA), with the reference's left-aligned copy placement.
 *
 * This holds the ONLY `priority` image on the homepage — it is the LCP element.
 *
 * PLACEHOLDER IMAGE: both crops are a free-licence stock photo (see
 * `public/images/stock/CREDITS.md`), standing in until the business supplies
 * photography of its own work. It is not a Living Space interior, so the alt
 * text describes the room without claiming it. Replace both files with crops of
 * a finished villa project, keeping the calmer side on the left where the
 * headline sits.
 *
 * ── WHY THERE ARE TWO CROPS (art direction) ─────────────────────────────────
 * On a phone the hero box is tall and narrow (~390×640), so a 16:9 image set to
 * `object-cover` is scaled by HEIGHT — drawn ~1140px wide with only its middle
 * third on screen. With one landscape source that is a lose-lose: `sizes="100vw"`
 * made a 3× phone fetch a 1200px rendition and stretch it ~3×, which is visibly
 * soft; an honest `sizes` would make it download a ~3800px landscape image to
 * show a third of it. So phones get their own portrait crop (`hero-mobile.jpg`,
 * 1290×2100, cut from the 6000px original — enough for a 430px-wide 3× screen)
 * and download only that.
 *
 * `next/image` cannot switch sources per breakpoint, so this uses Next's
 * documented art-direction pattern: `getImageProps()` for each source, rendered
 * into a `<picture>`. Both sources still go through the image optimizer — same
 * AVIF/WebP, same srcset — and the `<img>` is generated by Next, not hand-built.
 * It is the one place in the app that renders `<img>` directly.
 *
 * `sizes` for the landscape source: below a 4:3 viewport (portrait tablets) the
 * box is again height-driven, drawn at ~76vh × 16/9 ≈ 136vh wide; wider than
 * that it fills the width.
 *
 * Height is capped in `vh` but also floored in `rem`, so a short landscape phone
 * viewport can't crush the headline into the CTA.
 */
const HERO_ALT =
  "A living room with a long cream sectional sofa in front of a dark marble-effect wall with gold trim and wall lights";

export function Hero() {
  const shared = {
    alt: HERO_ALT,
    fill: true,
    // `priority` only stops lazy-loading here. The <Image> component adds the
    // high-priority hint (with a preload) itself; getImageProps doesn't, so
    // it's set explicitly — this is the LCP image. The <img> is in the server
    // HTML, so the preload scanner finds the right <source> early regardless.
    priority: true,
    fetchPriority: "high",
    className: "object-cover object-center",
  } as const;

  const {
    props: { srcSet: mobileSrcSet, sizes: mobileSizes },
  } = getImageProps({
    ...shared,
    src: "/images/stock/hero-mobile.jpg",
    sizes: "100vw",
  });
  const { props: desktop } = getImageProps({
    ...shared,
    src: "/images/stock/hero.jpg",
    sizes: "(max-aspect-ratio: 4/3) 136vh, 100vw",
  });

  return (
    <section className="relative flex min-h-[30rem] items-end overflow-hidden bg-bg-alt h-[76vh] max-h-[46rem] sm:items-center">
      <picture>
        {/* Matches the `sm` breakpoint, where the layout and scrim switch too. */}
        <source media="(max-width: 639px)" srcSet={mobileSrcSet} sizes={mobileSizes} />
        {/* eslint-disable-next-line jsx-a11y/alt-text -- alt (HERO_ALT) arrives in the getImageProps spread */}
        <img {...desktop} />
      </picture>
      {/*
        Scrim. Two elements rather than one with a `sm:` variant, because the
        scrim classes are plain component classes — Tailwind does not generate
        breakpoint variants for them, so `sm:scrim-left` would silently no-op.
        Mobile: gradient from the bottom, where the copy sits. Desktop: gradient
        from the left, since the copy is left-aligned and vertically centred.
      */}
      <div className="scrim-bottom absolute inset-0 sm:hidden" aria-hidden="true" />
      <div className="scrim-left absolute inset-0 hidden sm:block" aria-hidden="true" />

      <div className="on-dark shell relative z-10 pb-12 sm:pb-0">
        <div className="max-w-xl">
          <p className="eyebrow text-ink-inverse/85">Custom-made furniture · UAE</p>
          <h1 className="mt-4 text-ink-inverse">Made to measure for the way you live</h1>
          <p className="mt-5 max-w-md text-[0.9375rem] leading-relaxed text-ink-inverse/90">
            Majlis, sofas, TV units and bed walls — built to your size, fabric and
            finish, for villas and homes across the Emirates.
          </p>
          <ButtonLink
            href="/shop"
            variant="outline-inverse"
            size="lg"
            className="mt-8"
          >
            Explore the collection
          </ButtonLink>
        </div>
      </div>
    </section>
  );
}
